#!/usr/bin/env python3
"""Export the compact GeoNames-based place file used by `FilePlaceResolver`.

Reads Voyager's committed place data (travel-planner `backend/app/db/data/`, read-only) and
writes, into `crates/vc-extract/data/`:

* `places.tsv.gz`    populated places (GeoNames, >= 1,000 people) + notable features
* `countries.tsv.gz` country code, name and folded names (country hints)
* `admin1.tsv.gz`    first-level admin codes and names
* `NOTICE`           sources, licences and the GeoNames attribution

With `--rust-fold-table` it also regenerates `src/fold_table.rs`, so the Rust `fold()` and the
folded keys written here use the same character table.

Contains data from GeoNames (geonames.org), CC BY 4.0. The output is gzip with mtime 0, so a
re-run on the same input is byte-identical.

Usage: python3 scripts/export_places.py --src ~/travel-planner/backend/app/db/data [--rust-fold-table]
"""

from __future__ import annotations

import argparse
import csv
import gzip
import io
import sys
import unicodedata
from pathlib import Path

ATTRIBUTION = "Contains data from GeoNames (geonames.org), CC BY 4.0"
CRATE = Path(__file__).resolve().parent.parent

# Characters folded by hand (no NFKD decomposition, or a better one than stripping marks).
SPECIAL = {
    "ß": "ss", "ẞ": "ss", "ø": "o", "æ": "ae", "œ": "oe", "ł": "l", "đ": "d", "ð": "d",
    "þ": "th", "ı": "i", "ə": "e", "ɛ": "e", "ħ": "h", "ƶ": "z", "ŧ": "t", "ŀ": "l",
    "ĸ": "k", "ŋ": "n", "ſ": "s", "ɨ": "i", "ʉ": "u", "ɔ": "o", "ƒ": "f",
}
QUOTES = set("'’‘ʼʻ`ʹ“”\"´")
SPACERS = set(".·-‐‑‒–—―−_/,;:()[]")
TABLE_RANGES = [(0x00C0, 0x02AF), (0x1E00, 0x1EFF)]


def _table() -> dict[str, str]:
    t: dict[str, str] = {}
    for lo, hi in TABLE_RANGES:
        for cp in range(lo, hi + 1):
            c = chr(cp)
            low = c.lower()
            if len(low) != 1:
                continue
            if low in SPECIAL:
                t[c] = SPECIAL[low]
                continue
            base = "".join(
                ch for ch in unicodedata.normalize("NFKD", low) if not unicodedata.combining(ch)
            )
            if base and base != low and base.isascii() and base.isalpha():
                t[c] = base
    for k, v in SPECIAL.items():
        t[k] = v
    return t


TABLE = _table()


def fold(s: str) -> str:
    """Mirror of `vc_extract::fold::fold` (char by char, same table)."""
    out = []
    for c in s:
        if c in TABLE:
            out.append(TABLE[c])
            continue
        low = c.lower()
        if low in TABLE:
            out.append(TABLE[low])
        elif unicodedata.combining(c) or c in QUOTES or unicodedata.category(c) == "Cf":
            continue
        elif c in SPACERS or c.isspace():
            out.append(" ")
        elif low.isalnum():
            out.append(low)
        else:
            out.append(" ")
    return " ".join("".join(out).split())


def rust_table() -> str:
    rows = "\n".join(
        f"    ('\\u{{{ord(k):04x}}}', \"{v}\")," for k, v in sorted(TABLE.items(), key=lambda kv: ord(kv[0]))
    )
    return (
        "//! Generated by `scripts/export_places.py --rust-fold-table`; do not edit.\n"
        "//! Single characters folded to ASCII (NFKD without marks, plus hand-picked letters).\n\n"
        "/// Sorted by code point (binary-searchable).\n"
        f"pub(crate) static FOLD_TABLE: &[(char, &str)] = &[\n{rows}\n];\n"
    )


def gz_writer(path: Path):
    raw = open(path, "wb")
    gz = gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9)
    return raw, gz, io.TextIOWrapper(gz, encoding="utf-8", newline="\n")


def keys_of(*names: str) -> str:
    seen: list[str] = []
    for n in names:
        for part in n.split("|"):
            f = fold(part)
            if f and f not in seen:
                seen.append(f)
    return "|".join(seen)


def export(src: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    header = f"# {ATTRIBUTION}. Modified: filtered, names folded, ranked (see NOTICE).\n"

    raw, gz, w = gz_writer(out / "places.tsv.gz")
    w.write(header)
    w.write("geoname_id\tname\tcountry\tadmin1\tfclass\trank\tlat\tlon\tkeys\n")
    n = 0
    with gzip.open(src / "places.csv.gz", "rt", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            keys = keys_of(r["name"], r["ascii"], r["alt_names"])
            w.write(
                f"{r['geonameid']}\t{r['name']}\t{r['country_code']}\t{r['admin1']}\tP\t"
                f"{int(r['score'])}\t{float(r['lat']):.4f}\t{float(r['lng']):.4f}\t{keys}\n"
            )
            n += 1
    with gzip.open(src / "features.csv.gz", "rt", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            notability = int(r["notability"] or 0)
            pop = int(r["population"] or 0)
            rank = max(pop, 1000) * (notability + 1) ** 2
            keys = keys_of(r["name"], r["ascii"], r["alt_names"])
            w.write(
                f"{r['geonameid']}\t{r['name']}\t{r['country_code']}\t{r['admin1']}\t"
                f"{r['feature_code']}\t{rank}\t{float(r['lat']):.4f}\t{float(r['lng']):.4f}\t{keys}\n"
            )
            n += 1
    w.close(); gz.close(); raw.close()

    raw, gz, w = gz_writer(out / "countries.tsv.gz")
    w.write(header)
    w.write("code\tname\tkeys\n")
    with open(src / "countries.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            w.write(f"{r['code']}\t{r['name']}\t{keys_of(r['name'], r['names'])}\n")
    w.close(); gz.close(); raw.close()

    raw, gz, w = gz_writer(out / "admin1.tsv.gz")
    w.write(header)
    w.write("code\tname\n")
    with open(src / "admin1.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            w.write(f"{r['code']}\t{r['name']}\n")
    w.close(); gz.close(); raw.close()

    (out / "NOTICE").write_text(
        "Place data for vc-extract's FilePlaceResolver\n"
        "=============================================\n\n"
        f"{ATTRIBUTION}\n"
        "Licence: https://creativecommons.org/licenses/by/4.0/\n\n"
        "places.tsv.gz, admin1.tsv.gz and the folded names of countries.tsv.gz are derived from\n"
        "GeoNames (cities1000, admin1CodesASCII, allCountries; snapshots 2026-10-29/30) via\n"
        "Voyager's committed place data (rupakc/travel-planner, backend/app/db/data). The data\n"
        "is MODIFIED: places filtered (>= 1,000 people, some feature codes dropped), notable\n"
        "non-town features kept, names folded to ASCII keys, places ranked, coordinates rounded\n"
        "to 4 decimals. GeoNames does not endorse these changes.\n\n"
        "Country codes and names (countries.tsv.gz `code`, `name`) come from OurAirports\n"
        "(https://ourairports.com/data/), public domain.\n\n"
        "Regenerate with: python3 crates/vc-extract/scripts/export_places.py --src <data dir>\n",
        encoding="utf-8",
    )
    print(f"wrote {n} places/features to {out}", file=sys.stderr)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--src", type=Path, required=True, help="travel-planner backend/app/db/data")
    ap.add_argument("--out", type=Path, default=CRATE / "data")
    ap.add_argument("--rust-fold-table", action="store_true", help="also write src/fold_table.rs")
    a = ap.parse_args()
    export(a.src, a.out)
    if a.rust_fold_table:
        (CRATE / "src" / "fold_table.rs").write_text(rust_table(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
