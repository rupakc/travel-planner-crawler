# Per-source class for batch-2 sources (set by _src below).
SOURCE_CLASS: dict[str, str] = {}


def source_class(sid: str) -> str:
    if sid in SOURCE_CLASS:
        return SOURCE_CLASS[sid]
    if sid in OFFICIAL:
        return "official"
    if sid in COMMERCIAL_API:
        return "commercial_api"
    if sid in COMMUNITY:
        return "community"
    if sid in EDITORIAL or sid.startswith(("blog-", "news-")):
        return "editorial"
    return "reference"  # Wikipedia/Wikidata/OSM, open datasets and catalogues


