# Generation
# ---------------------------------------------------------------------------------------
def build_spec(seed: dict) -> dict:
    sid = seed["id"]
    lic = seed["license"]
    if lic not in LICENCES:
        raise MappingError(f"{sid}: unmapped licence string {lic!r}; add it to LICENCES")
    lclass, spdx, lurl = LICENCES[lic]
    method = seed["method"]
    if method not in METHODS:
        raise MappingError(f"{sid}: unknown method {method!r}")
    if seed["cadence"] not in CADENCE:
        raise MappingError(f"{sid}: unknown cadence {seed['cadence']!r}")
    category = seed["category"]
    if category not in KINDS_BY_CATEGORY and sid not in KINDS_OVERRIDE:
        raise MappingError(f"{sid}: no kinds for category {category!r}")

    url = SEED_URL_OVERRIDE.get(sid, seed["url"])
    seeds, sitemaps, feeds = [], [], []
    {"rss": feeds, "sitemap": sitemaps}.get(method, seeds).append(url)

    kinds = KINDS_OVERRIDE.get(sid, KINDS_BY_CATEGORY.get(category, []))
    llm_kinds = LLM_KINDS_OVERRIDE.get(sid, LLM_KINDS_BY_CATEGORY.get(category, []))
    if not set(llm_kinds) <= set(kinds) or not set(kinds) <= KINDS:
        raise MappingError(f"{sid}: bad kinds {kinds} / llm_kinds {llm_kinds}")

    attribution = ATTRIBUTION.get(sid)
    if attribution is None:
        tmpl = ATTRIBUTION_BY_SPDX.get(spdx or "")
        attribution = tmpl.format(name=seed["name"]) if tmpl else seed["name"]

    notes = [n for n in (seed.get("notes") or "",) if n]
    if sid in SEED_URL_OVERRIDE:
        notes.append(f"URL template: {seed['url']}")
    enabled = True
    if lclass == "restricted":
        enabled = False
        notes.append("Disabled: restricted licence (non-commercial or unknown), not ingested in v1 (spec §5.9).")
    elif sid in DISABLED:
        enabled = False
        notes.append(f"Disabled: {DISABLED[sid]}")
    if seed["cadence"] in {"never", "semiannual", "on_change", "4x_daily", "hourly_cache"}:
        notes.append(f"Research cadence: {seed['cadence']}.")

    needs_key = bool(seed["needs_key"])
    max_depth = {"rss": 1, "sitemap": 1, "html": 2}.get(method, 0)

    spec: dict = {
        "id": sid,
        "name": seed["name"],
        "category": category,
        "source_class": source_class(sid),
        "licence": {"class": lclass, "spdx": spdx, "attribution": attribution, "url": lurl},
        "method": method,
        "seeds": seeds,
        "sitemaps": sitemaps,
        "feeds": feeds,
        "adapter": ADAPTERS.get(sid),
        "include": [],
        "exclude": EXCLUDE.get(sid, []),
        "max_depth": max_depth,
        "kinds": list(kinds),
        "llm_kinds": list(llm_kinds),
        "render": "never",
        "cadence": CADENCE[seed["cadence"]],
        "min_delay_s": MIN_DELAY.get(sid, 5),
        "daily_budget": 3000,
        "politeness_key": None,
        "enabled": enabled,
        "needs_key": needs_key,
        "key_secret": f"crawler-src-{sid}-key" if needs_key else None,
        "max_retention_days": MAX_RETENTION_DAYS.get(sid),
        "display_requirements": DISPLAY_REQUIREMENTS.get(sid),
        "notes": " | ".join(notes) or None,
    }
    return spec


def generate(seeds_path: Path, out_dir: Path, denylist_path: Path) -> list[Path]:
    seeds = yaml.safe_load(Path(seeds_path).read_text())["seeds"]
    deny = load_denylist(denylist_path)
    out_dir = Path(out_dir)
    specs = []
    for seed in seeds:
        if not seed["allowed"]:
            continue
        spec = build_spec(seed)
        for u in spec["seeds"] + spec["sitemaps"] + spec["feeds"]:
            hit = denied(u, deny)
            if hit:
                raise MappingError(f"{spec['id']}: {u} is denylisted ({hit['reason']})")
        specs.append(spec)
    ids = [s["id"] for s in specs]
    if len(ids) != len(set(ids)):
        raise MappingError("duplicate seed ids")
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for spec in specs:
        path = out_dir / f"{spec['id']}.yaml"
        body = yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=100)
        path.write_text(HEADER + body)
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seeds", default=ROOT / "docs/research/seeds.yaml", type=Path)
    ap.add_argument("--out", default=ROOT / "sources", type=Path)
    ap.add_argument("--denylist", default=ROOT / "policy/denylist.yaml", type=Path)
    args = ap.parse_args(argv)
    try:
        written = generate(args.seeds, args.out, args.denylist)
    except MappingError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    enabled = sum(1 for p in written if re.search(r"^enabled: true$", p.read_text(), re.M))
    print(f"wrote {len(written)} sources ({enabled} enabled, {len(written) - enabled} disabled) to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
