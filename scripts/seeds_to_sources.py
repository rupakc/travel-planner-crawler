# ---------------------------------------------------------------------------------------
# Denylist matching (Python mirror of the rule vc-policy implements with the PSL).
# ---------------------------------------------------------------------------------------
def load_denylist(path: Path) -> list[dict]:
    data = yaml.safe_load(Path(path).read_text())
    entries = data["entries"]
    for e in entries:
        missing = {"host", "reason", "source"} - set(e)
        if missing:
            raise MappingError(f"denylist entry {e} lacks {sorted(missing)}")
    return entries


def _host_matches(host: str, pattern: str) -> bool:
    host = host.lower().rstrip(".")
    pattern = pattern.lower()
    if pattern.endswith(".*"):
        brand = pattern[:-2]
        labels = host.split(".")
        for i, label in enumerate(labels):
            suffix = labels[i + 1:]
            # brand label directly under a public suffix such as com, co.uk, de, com.au
            if label == brand and 1 <= len(suffix) <= 2 and all(len(x) <= 3 for x in suffix):
                return True
        return False
    return host == pattern or host.endswith("." + pattern)


def denied(url: str, entries: list[dict]) -> dict | None:
    parts = urlsplit(url)
    host = parts.hostname or ""
    path = parts.path or "/"
    for e in entries:
        if any(_host_matches(host, x) for x in e.get("except_hosts", [])):
            continue
        if _host_matches(host, e["host"]) and path.startswith(e.get("path_prefix", "/")):
            return e
    return None


