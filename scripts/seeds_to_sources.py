#!/usr/bin/env python3
"""Generate sources/<id>.yaml (one per allowed seed) from docs/research/seeds.yaml.

Usage:
    python3 scripts/seeds_to_sources.py [--seeds docs/research/seeds.yaml]
                                        [--out sources] [--denylist policy/denylist.yaml]

Mappings follow the design spec: licence classes §5.9 + §17.8, source classes §17.8,
forums §5.10, kinds §5.7, adapters plan Task 10. Every licence string in seeds.yaml
must be mapped explicitly below; an unknown string raises MappingError instead of
guessing. Restricted sources (non-commercial or unknown terms) are written with
enabled: false. Disallowed seeds never get a file: they live in policy/denylist.yaml.

After P0 the generated files may be edited by hand (Task 10, Task 18); re-running the
script overwrites the seed-derived files, so put lasting changes in the tables here.
"""

