def source_class(sid: str) -> str:
    if sid in OFFICIAL:
        return "official"
    if sid in COMMERCIAL_API:
        return "commercial_api"
    if sid in COMMUNITY:
        return "community"
    if sid in EDITORIAL or sid.startswith(("blog-", "news-")):
        return "editorial"
    return "reference"  # Wikipedia/Wikidata/OSM, open datasets and catalogues


