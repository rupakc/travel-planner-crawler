#!/usr/bin/env python3
"""Generate the source registry (docs/SOURCES.md and the wiki page docs/wiki/Sources.md)
from sources/*.yaml.

Usage:
    python3 scripts/sources_doc.py           # rewrite both files
    python3 scripts/sources_doc.py --check   # exit 1 when either file is out of date

The registry lists every source under each app section it serves (from `relevance`), so the
list cannot grow silently: CI (scripts/tests/test_sources_doc.py) fails when a spec changes
and the doc was not regenerated.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from urllib.parse import urlsplit

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = (ROOT / "docs" / "SOURCES.md", ROOT / "docs" / "wiki" / "Sources.md")

# App section -> heading, in the order the Voyager app shows them.
SECTION_TITLES = {
    "flights": "Flights",
    "weather": "Weather",
    "hotels": "Hotels",
    "activities": "Activities",
    "places": "Places to see",
    "walking_tours": "Free walking tours",
    "events": "Events",
    "visa": "Visa and travel advice",
    "sim": "SIM cards",
    "tips": "Travel tips",
    "emergency_card": "Emergency card",
    "getting_around": "Local transportation",
    "forex": "Forex",
    "packing": "Packing list",
    "itinerary": "Itinerary",
}

LICENCE_WORDS = {
    "open": "open",
    "share_alike": "share-alike",
    "facts_only": "facts only",
    "api_terms": "API terms",
    "restricted": "restricted",
}


def load_specs(sources_dir: Path) -> list[dict]:
    return [yaml.safe_load(p.read_text()) for p in sorted(Path(sources_dir).glob("*.yaml"))]


def hosts(spec: dict) -> list[str]:
    out: list[str] = []
    for u in spec.get("seeds", []) + spec.get("sitemaps", []) + spec.get("feeds", []):
        h = urlsplit(u).hostname or ""
        if h and h not in out:
            out.append(h)
    return out


def _cell(s: str) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def render(specs: list[dict]) -> str:
    on = sum(1 for s in specs if s.get("enabled", True))
    lines = [
        "# Sources",
        "",
        "<!-- Generated by scripts/sources_doc.py from sources/*.yaml. Do not edit by hand:",
        "     change the specs (scripts/seeds_to_sources.py tables), then run",
        "     python3 scripts/sources_doc.py. CI fails when this file is out of date. -->",
        "",
        "Every website and dataset the crawler knows, grouped by the part of the Voyager app it",
        "feeds. A source that serves several parts is listed under each of them.",
        "",
        f"**{len(specs)} sources, {on} on, {len(specs) - on} off.**",
        "",
        "- **What we take**: the traveller-facing data the source gives (its `relevance.why`).",
        "- **Licence**: *open* (free reuse with credit), *share-alike* (kept apart from other",
        "  licences), *facts only* (facts, headline, a short excerpt and a link, never the full",
        "  text), *API terms* (the provider's terms), *restricted* (never collected).",
        "- **On**: whether the crawler uses it now. **Key**: whether it needs an API key.",
        "",
        "A new source must name the app section(s) it serves and why, must be about travel, and",
        "is added only with the owner's approval (see CONTRIBUTING.md).",
        "",
    ]
    for section, title in SECTION_TITLES.items():
        rows = [s for s in specs if section in (s.get("relevance") or {}).get("sections", [])]
        if not rows:
            continue
        rows.sort(key=lambda s: (not s.get("enabled", True), s["id"]))
        lines += [f"## {title}", "", "| Source | Website | What we take | Licence | On | Key |",
                  "|---|---|---|---|---|---|"]
        for s in rows:
            lines.append(
                "| `{}` | {} | {} | {} | {} | {} |".format(
                    s["id"],
                    ", ".join(f"`{h}`" for h in hosts(s)) or "-",
                    _cell(s["relevance"]["why"]),
                    LICENCE_WORDS.get(s["licence"]["class"], s["licence"]["class"]),
                    "yes" if s.get("enabled", True) else "no",
                    "yes" if s.get("needs_key") else "no",
                )
            )
        lines.append("")
    missing = sorted(s["id"] for s in specs if not s.get("relevance"))
    if missing:
        lines += ["## Missing relevance", "", *(f"- `{m}`" for m in missing), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sources", default=ROOT / "sources", type=Path)
    ap.add_argument("--check", action="store_true", help="fail when a file is out of date")
    args = ap.parse_args(argv)
    text = render(load_specs(args.sources))
    stale = [p for p in OUTPUTS if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 scripts/sources_doc.py",
                  file=sys.stderr)
        return 1 if stale else 0
    for p in OUTPUTS:
        p.write_text(text)
    print(f"wrote {', '.join(str(p.relative_to(ROOT)) for p in OUTPUTS)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
